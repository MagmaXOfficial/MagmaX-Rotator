const BY_ID = new Map(PROVIDERS.map((p) => [p.id, p]));

export function getProviderDefinition(id: string): ProviderDefinition | undefined {
  return BY_ID.get(id);
}

export function listProviderDefinitions(): ProviderDefinition[] {
  return PROVIDERS;
}

export function resolveBaseUrl(def: ProviderDefinition, baseUrl: string, accountId: string | null): string {
  const trimmed = (baseUrl || def.baseUrl).replace(/\/+$/, '');
  return trimmed.replace('{accountId}', accountId ?? '');
}
